def code(src: str, tags=None) -> dict:
    cell = {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [],
            "source": src.splitlines(keepends=True)}
    if tags:
        cell["metadata"]["tags"] = tags
    return cell


def build(out: Path, replacements: dict | None = None):
    engine = (ROOT / "src" / "recon_engine.py").read_text(encoding="utf-8")
    engine = engine.replace("from __future__ import annotations\n", "")   # must be first in a cell
    params = PARAMS
    for k, v in (replacements or {}).items():
        params = params.replace(k, v)
    nb = {
        "nbformat": 4, "nbformat_minor": 5,
        "metadata": {
            "kernel_info": {"name": "synapse_pyspark"},
            "kernelspec": {"name": "synapse_pyspark", "display_name": "Synapse PySpark"},
            "language_info": {"name": "python"},
        },
        "cells": [
            {"cell_type": "markdown", "metadata": {}, "source": HEADER_MD.splitlines(keepends=True)},
            code(params, tags=["parameters"]),
            code("# ===== Matching engine (generated from src/recon_engine.py) =====\n" + engine),
            code(IO),
            code(RUN),
            code(EXIT),
        ],
    }
    out.parent.mkdir(exist_ok=True)
    out.write_text(json.dumps(nb, indent=1), encoding="utf-8")
    return out


